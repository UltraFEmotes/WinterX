package winterx.legacyboot;

/**
 * The whole page around the emulator: only the phone's screen, scaled to fit, with touches, sound and a loading line.
 * Hardware buttons come from Android keys (see IPhoneOS). The worker protocol is kelindi's emu-worker.js.
 */
final class Page {
    static final String HTML = String.join("\n",
        "<!doctype html><html><head><meta charset=utf-8>",
        "<meta name=viewport content='width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no'>",
        "<style>",
        "html,body{margin:0;height:100%;background:#000;overflow:hidden;touch-action:none;user-select:none;-webkit-user-select:none}",
        "canvas{position:absolute;image-rendering:pixelated}",
        // The iPhone's round Home button, under its screen.
        "#home{position:absolute;border-radius:50%;background:radial-gradient(circle at 50% 35%,#2a2a2c,#0b0b0c 70%);",
        "box-shadow:inset 0 0 0 2px #3a3a3c,0 0 0 1px #000;touch-action:none}",
        "#home::after{content:'';position:absolute;left:31%;top:31%;width:38%;height:38%;border:2px solid #77777a;border-radius:22%;box-sizing:border-box}",
        "#home.down{background:radial-gradient(circle at 50% 35%,#3a3a3d,#151516 70%)}",
        "#status{position:absolute;left:24px;right:24px;top:50%;transform:translateY(-50%);color:#8a8a8a;",
        "font:15px -apple-system,Helvetica,Arial,sans-serif;text-align:center;line-height:1.5}",
        "</style></head><body>",
        "<canvas id=screen width=320 height=480></canvas><div id=home></div><div id=status>Starting iPhone OS 1…</div>",
        "<script>",
        "const screen=document.getElementById('screen'),paint=screen.getContext('2d'),image=paint.createImageData(320,480);",
        "const status=document.getElementById('status'),contacts=new Map();",
        "let ready=false,sequence=0,audio=null,audioTime=0;",
        // The screen fills the width at the top; the Home button sits centred in the space below it.
        "const home=document.getElementById('home');",
        "function fit(){const W=innerWidth,H=innerHeight,zone=Math.max(H*0.12,64);",
        "  const k=Math.min(W/320,(H-zone)/480),sw=320*k,sh=480*k,left=(W-sw)/2;",
        "  Object.assign(screen.style,{width:sw+'px',height:sh+'px',left:left+'px',top:'0px'});",
        "  const below=H-sh,d=Math.max(36,Math.min(below*0.62,sw*0.2));",
        "  Object.assign(home.style,{width:d+'px',height:d+'px',left:(W-d)/2+'px',top:sh+(below-d)/2+'px'});}",
        "addEventListener('resize',fit);fit();",
        "const worker=new Worker('emu-worker.js');",
        "const bridge=window.LegacyBoot||{ready(){},stopped(){}};",
        "worker.onerror=e=>{status.hidden=false;status.textContent=e.message||'The emulator failed to start';bridge.stopped(status.textContent);};",
        "worker.onmessage=({data:m})=>{",
        "  if(m.type==='frame'){image.data.set(new Uint8Array(m.buffer));paint.putImageData(image,0,0);",
        "    worker.postMessage({type:'recycle',buffer:m.buffer},[m.buffer]);}",
        "  else if(m.type==='audio')play(m.rate,m.buffer);",
        "  else if(m.type==='loading'){status.textContent=m.message+(m.total>0?' ('+Math.min(99,Math.floor(m.received/m.total*100))+'%)':'');}",
        "  else if(m.type==='ready'){ready=true;status.hidden=true;bridge.ready();}",
        "  else if(m.type==='fatal'){ready=false;status.hidden=false;status.textContent=m.message;bridge.stopped(m.message);}",
        "};",
        "worker.postMessage({type:'start',id:++sequence,cpi:1,checkpoint:null});",
        "function unlock(){const C=window.AudioContext||window.webkitAudioContext;",
        "  if(!audio&&C)audio=new C({latencyHint:'interactive'});if(audio&&audio.state==='suspended')audio.resume().catch(()=>{});}",
        "for(const t of ['pointerdown','keydown','touchend'])document.addEventListener(t,unlock,{capture:true,passive:true});",
        "function play(rate,buffer){if(!audio||audio.state!=='running')return;",
        "  const pcm=new Int16Array(buffer),frames=pcm.length>>1;if(!frames||!rate)return;",
        "  const out=audio.createBuffer(2,frames,rate),l=out.getChannelData(0),r=out.getChannelData(1);",
        "  for(let i=0;i<frames;i++){l[i]=pcm[2*i]/32768;r[i]=pcm[2*i+1]/32768;}",
        "  const now=audio.currentTime;if(audioTime<now+0.01||audioTime>now+0.5)audioTime=now+0.04;",
        "  const s=audio.createBufferSource();s.buffer=out;s.connect(audio.destination);s.start(audioTime);audioTime+=frames/rate;}",
        "function point(e){const r=screen.getBoundingClientRect();",
        "  return{x:Math.max(0,Math.min(319,Math.floor((e.clientX-r.left)*320/r.width))),",
        "    y:Math.max(0,Math.min(479,Math.floor((e.clientY-r.top)*480/r.height)))};}",
        "function send(){worker.postMessage({type:'contacts',id:++sequence,contacts:[...contacts.values()]});}",
        "home.addEventListener('pointerdown',e=>{e.stopPropagation();e.preventDefault();home.classList.add('down');button(1,true);});",
        "for(const t of ['pointerup','pointercancel','pointerleave'])home.addEventListener(t,e=>{if(!home.classList.contains('down'))return;",
        "  home.classList.remove('down');button(1,false);});",
        "document.addEventListener('pointerdown',e=>{if(!ready||e.target===home)return;",
        "  const used=new Set([...contacts.values()].map(c=>c.id)),id=[1,2,3,4,5].find(n=>!used.has(n));if(!id)return;",
        "  contacts.set(e.pointerId,{id,...point(e)});send();e.preventDefault();});",
        "document.addEventListener('pointermove',e=>{const c=contacts.get(e.pointerId);if(!c||!ready)return;Object.assign(c,point(e));send();e.preventDefault();});",
        "for(const t of ['pointerup','pointercancel'])document.addEventListener(t,e=>{if(contacts.delete(e.pointerId))send();});",
        // 0 Sleep/Wake, 1 Home, 2 volume up, 3 volume down
        "window.button=(which,pressed)=>{if(ready)worker.postMessage({type:'button',id:++sequence,which,pressed});};",
        "window.pausePhone=value=>{if(ready)worker.postMessage({type:'pause',id:++sequence,value});};",
        "</script></body></html>");
}
